"""Copy Leatrix Maps' dungeon map pins (its `dungeonPins` table: entrances,
level arrows and bosses with their portrait display IDs, keyed by game map
ID) into Map/Data/LeatrixDungeonPins.lua for Map/DungeonPins.lua.
2026-11-17 (user request: mark dungeon entrances with Leatrix's icons and
show boss portraits instead of skulls).

Rows, as in Leatrix:
  {"entrance", x, y, kind}              kind "raid" or nil
  {"level", x, y, mapID, up}            up true = the level above
  {"boss", x, y, npcID, name, level, displayID, style}
                                        style 2/4 = rare, 3 = level ??
x, y are 0-1 on the game's own map of that level.

Run again after Leatrix Maps updates:  python -I Tools/import_leatrix_dungeon_pins.py
"""
import io, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = r'G:\World of Warcraft\_forever_\Interface\AddOns\Leatrix_Maps\Leatrix_Maps.lua'
OUT = os.path.join(HERE, '..', 'Map', 'Data', 'LeatrixDungeonPins.lua')


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else SRC
    lines = io.open(src, encoding='utf-8').read().split('\n')
    start = next(i for i, l in enumerate(lines) if 'local dungeonPins = {' in l)
    depth, body = 0, []
    for i in range(start, len(lines)):
        l = lines[i]
        code = re.sub(r'--.*$', '', l) if '"' not in l.split('--')[0] or True else l
        depth += code.count('{') - code.count('}')
        body.append(l)
        if i > start and depth == 0:
            break
    text = '\n'.join(body)
    text = text.replace('local dungeonPins = {', 'AlchemyGPS.LeatrixDungeonPins = {', 1)
    text = re.sub(r'L\["((?:[^"\\]|\\.)*)"\]', r'"\1"', text)
    leftover = re.findall(r'\bL\[', text)
    assert not leftover, 'unhandled L[...]'
    text = '\n'.join(l.replace('\t\t\t', '', 1) for l in text.split('\n'))
    header = (
        '---------------------------------------------------------------------------------------\n'
        '-- Alchemy GPS | Map/Data/LeatrixDungeonPins.lua\n'
        '--\n'
        '-- GENERATED by Tools/import_leatrix_dungeon_pins.py from Leatrix Maps\'\n'
        '-- dungeon map pins (used with its author\'s permission, like its dungeon\n'
        '-- art). Do not edit by hand - re-run the tool. Read by Map/DungeonPins.lua.\n'
        '--   {"entrance", x, y, kind}               kind "raid" or nil\n'
        '--   {"level", x, y, mapID, up}             up true = the level above\n'
        '--   {"boss", x, y, npcID, name, level, displayID, style}  style 2/4 rare, 3 level ??\n'
        '---------------------------------------------------------------------------------------\n\n'
        'local AlchemyGPS = _G.AlchemyGPS\n\n')
    io.open(os.path.normpath(OUT), 'w', encoding='utf-8', newline='\n').write(header + text + '\n')
    print('wrote', os.path.normpath(OUT), text.count('{"boss"'), 'bosses',
          text.count('{"entrance"'), 'entrances', text.count('{"level"'), 'level arrows')


if __name__ == '__main__':
    main()
