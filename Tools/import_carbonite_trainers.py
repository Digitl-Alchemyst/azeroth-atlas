"""Write Map/Data/GuideTrainer.lua - class and profession trainer spots on
the map (2026-11-18, user request: Carbonite's trainer icons).

Source: Carbonite/Data/camelot/Guides/<Kind>Trainer.lua, one file per
trainer kind, each "Nx.GuideData[L["Mage Trainer"]] = { [mapId] =
"fac,x,y|fac,x,y", ... }" - the same shape as the Mailbox / Innkeeper /
Banker files Map/Data/Guide*.lua already carry (fac: 0 both, 1 Alliance
only, 2 Horde only; x and y map percent).

Written as two Guide data kinds, like Carbonite's two map switches
("Show Class Trainer" - your class only - and "Show Profession
Trainers"):
  GuideData.ClassTrainer       every class's trainers; the map shows
                               only your class's (MinimapEngine.lua)
  GuideData.ProfessionTrainer  every profession, riding, first aid,
                               cooking and fishing trainer
Each spot carries its kind as its name ("Mage Trainer"), which is the
icon's tooltip.

Run:  python -I Tools/import_carbonite_trainers.py   (from the addon
folder, with Carbonite installed beside it in R:\\addons)
"""
import glob
import io
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.normpath(os.path.join(HERE, '..'))
SRC = os.path.normpath(os.path.join(ADDON, '..', 'Carbonite', 'Data', 'camelot', 'Guides'))
OUT = os.path.join(ADDON, 'Map', 'Data', 'GuideTrainer.lua')

CLASSES = {'Druid', 'Hunter', 'Mage', 'Paladin', 'Priest', 'Rogue',
           'Shaman', 'Warlock', 'Warrior'}
# File names that aren't the plain profession name.
NAMES = {'FirstAid': 'First Aid'}


def main():
    kinds = {'ClassTrainer': {}, 'ProfessionTrainer': {}}
    counts = {'ClassTrainer': 0, 'ProfessionTrainer': 0}
    for path in sorted(glob.glob(os.path.join(SRC, '*Trainer.lua'))):
        stem = os.path.basename(path)[:-len('Trainer.lua')]
        name = NAMES.get(stem, stem)
        kind = 'ClassTrainer' if name in CLASSES else 'ProfessionTrainer'
        label = name + ' Trainer'
        src = io.open(path, encoding='utf-8').read()
        for mid, spots in re.findall(r'\[(\d+)\]\s*=\s*"([^"]*)"', src):
            for spot in spots.split('|'):
                parts = spot.split(',')
                if len(parts) < 3:
                    continue
                fac, x, y = parts[0], parts[1], parts[2]
                kinds[kind].setdefault(int(mid), []).append('%s,%s,%s,%s' % (fac, x, y, label))
                counts[kind] += 1

    out = [
        '-- Azeroth Atlas | Map/Data/GuideTrainer.lua',
        '-- GENERATED by Tools/import_carbonite_trainers.py - do not edit by hand.',
        '-- Class and profession trainer spots from Carbonite\'s camelot guide',
        '-- data, in the Guide data shape ([mapId] = "fac,x,y,name|...").',
        '',
        'local AzerothAtlas = _G.AzerothAtlas',
        'local Map = AzerothAtlas.Map',
        'Map.GuideData = Map.GuideData or {}',
        '',
    ]
    for kind in ('ClassTrainer', 'ProfessionTrainer'):
        out.append('Map.GuideData["%s"] = {' % kind)
        out.append('    Mode = 32,')
        for mid in sorted(kinds[kind]):
            out.append('    [%d] = "%s",' % (mid, '|'.join(kinds[kind][mid])))
        out.append('}')
        out.append('')
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    print('wrote %s: %d class, %d profession trainer spots'
          % (OUT, counts['ClassTrainer'], counts['ProfessionTrainer']))


if __name__ == '__main__':
    main()
