"""Regenerates AlchemyGPS/Quest/Data/*.lua from Carbonite's quest data.

Source (GPL-3.0, read-only):
    Carbonite.Quests/Data/camelot/Quests<range>.lua   quest rows
    Carbonite.Quests/Data/camelot/QuestStartEnd*.lua  giver/ender id -> name
    Carbonite.Quests/Data/camelot/QuestNPC.lua        legacy name fallback
    Carbonite.Quests/Data/camelot/Quest{Start,End}Alts.lua
    Carbonite.Quests/Data/camelot/QuestRequiredClasses.lua
    Carbonite.Quests/Data/Shared/QuestPrev.lua
    Carbonite/Data/camelot/Zones.lua                  dungeon entrances
    QuestieDB/QuestieDB_Forever.toc, support/Forever/Zones/*
                                                      which dungeon an objective,
                                                      giver or turn-in is inside

Every packed string ("npc|map|32|x|y", "name|map|35|x|y|w|h", the quest
header) is copied as its original source text, never re-typed or re-escaped,
so the ported parser in Quest/QuestCatalog.lua reads exactly what Carbonite's
own does. Only the wrapper around the rows changes: nothing is written to a
global, everything hangs off AlchemyGPS.QuestData.

Usage (from anywhere):
    python Tools/gen_quest_data.py [--addons R:\\addons]
"""
import argparse
import re
import sys
from pathlib import Path

QUEST_FILES = [
    ("Quests1-10.lua", "QuestDB1.lua"),
    ("Quests11-20.lua", "QuestDB2.lua"),
    ("Quests21-30.lua", "QuestDB3.lua"),
    ("Quests31-40.lua", "QuestDB4.lua"),
    ("Quests41-50.lua", "QuestDB5.lua"),
    ("Quests51-60.lua", "QuestDB6.lua"),
]

QUEST_RE = re.compile(r"^        \[(-?\d+)\] = \{\s*$")
FIELD_RE = re.compile(r"^            (Quest|Start|End) = (.*?),\s*$")
OBJ_OPEN_RE = re.compile(r"^            Objectives = \{\s*$")
OBJ_IDX_RE = re.compile(r"^                \[(\d+)\] = \{\s*$")
OBJ_LINE_RE = re.compile(r'^                    (".*"),\s*$')
KV_RE = re.compile(r"^\s*\[(\d+)\]\s*=\s*(.+?),?\s*$")
ZONE_RE = re.compile(
    r'^\s*\[(\d+)\] = L\["(.*)"\] \.\. "\|\d+\|\d+\|\d+\|5\|(\d+)\|([\d.]+)\|([\d.]+)\|\d+",')

# Onyxia's Lair is listed under owner map 70 in Zones.lua. Every other row
# uses this client's 14xx zone ids, and 70 is not one of them; the entrance
# coordinates given (52.41, 76.39) are the lair's entrance in Dustwallow
# Marsh, which is 1445 here.
OWNER_MAP_FIXES = {70: 1445}

# Instance id -> (x, y): an entrance Zones.lua places wrongly. The Drowned
# City's underwater entrance is at about 21.5, 27.8 in Stranglethorn Vale
# (checked in game by the user, 2026-11-16; DungeonGuideForever has 21.4,
# 27.9) - Zones.lua's 20.9, 28.1 is short of it.
ENTRANCE_FIXES = {2970: ("21.5", "27.8")}

# 2026-11-16 (user: Wailing Caverns' entrance not on the map while in the
# Barrens). Zones.lua has these at the places of the later, redrawn zone
# maps (Northern Barrens, Northern Stranglethorn, the remade Orgrimmar) on
# this client's classic maps - Wailing Caverns ended up south of Camp
# Taurajo. Replaced where Forever Dungeon Routes' and Dungeon Crawler
# Forever's entrance lists agree with each other and not with Zones.lua.
# Blackrock Mountain's four stay on Burning Steppes (ZONE_ALIASES below):
# BRS / BWL at FDR's portal, BRD / MC at DCF's Burning Steppes point.
ENTRANCE_FIXES.update({
    213: ("53.2", "48.7"),   # Ragefire Chasm
    232: ("32.5", "30.0"),   # Molten Core
    234: ("62.0", "33.3"),   # Dire Maul
    242: ("32.5", "30.0"),   # Blackrock Depths
    250: ("36.5", "25.4"),   # Blackrock Spire
    279: ("46.0", "36.3"),   # Wailing Caverns
    287: ("36.5", "25.4"),   # Blackwing Lair
    300: ("50.9", "92.9"),   # Razorfen Downs
    337: ("53.9", "17.6"),   # Zul'Gurub
    435: ("85.1", "31.4"),   # Scarlet Monastery
})

# Blackrock Mountain's four instances are listed under Burning Steppes in
# Zones.lua, while the quest rows put objectives inside them under Searing
# Gorge (the first approach QuestieDB lists).
ZONE_ALIASES = {1427: 1428}

# (quest id, zone) -> [instance ids], for a row resolve_dungeons() can't settle
# from QuestieDB. Empty while QuestieDB settles them all.
ROW_DUNGEONS = {}

# The map's own entrance flags. Quest routing sends the player to these, so
# they have to be the same instances at the same places as QuestData.Instances.
MAP_FLAG_RE = re.compile(r'^\s*\{\s*"([^"]+)",\s*(\d+),\s*([\d.]+),\s*([\d.]+)\s*\},')

HEADER = """-- AUTO-GENERATED by Tools/gen_quest_data.py. Do not edit by hand.
-- Source: {source}
-- {note}
-- Carbonite and Carbonite.Quests are GPL-3.0; this file is a data port.
"""


def parse_quest_file(path):
    """Returns [(questID, {"Quest":src, "Start":src, "End":src}, {idx:[src]})]."""
    rows = []
    cur = None
    cur_list = None
    in_data = False
    for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not in_data:
            if line.strip() == "local ModQuests = {":
                in_data = True
            continue
        if line.rstrip() == "    }":
            break
        m = QUEST_RE.match(line)
        if m:
            cur = (int(m.group(1)), {}, {})
            rows.append(cur)
            cur_list = None
            continue
        if cur is None:
            raise SystemExit("%s:%d: data before first quest: %r" % (path.name, lineno, line))
        m = FIELD_RE.match(line)
        if m:
            cur[1][m.group(1)] = m.group(2)
            continue
        m = OBJ_IDX_RE.match(line)
        if m:
            cur_list = cur[2].setdefault(int(m.group(1)), [])
            continue
        m = OBJ_LINE_RE.match(line)
        if m:
            if cur_list is None:
                raise SystemExit("%s:%d: objective row outside a list" % (path.name, lineno))
            cur_list.append(m.group(1))
            continue
        if OBJ_OPEN_RE.match(line) or line.strip() in ("},", "}"):
            continue
        raise SystemExit("%s:%d: unrecognised line: %r" % (path.name, lineno, line))
    return rows


def plain(src):
    """Source text of a Lua string literal -> its value (enough for '|' splits)."""
    src = src.strip()
    if src.startswith("[=["):
        return src[3:-3]
    return src[1:-1]


def emit_quest_file(out, source_name, rows):
    lines = [HEADER.format(
        source="Carbonite.Quests/Data/camelot/" + source_name,
        note="Quest rows: header, Start/End giver strings, objective location lists."),
        "local AlchemyGPS = _G.AlchemyGPS",
        "AlchemyGPS.QuestData = AlchemyGPS.QuestData or {}",
        "local QuestData = AlchemyGPS.QuestData",
        "QuestData.Chunks = QuestData.Chunks or {}",
        "QuestData.Chunks[#QuestData.Chunks + 1] = function()",
        "return {",
    ]
    for qid, fields, objs in rows:
        parts = []
        for key in ("Quest", "Start", "End"):
            if key in fields:
                parts.append("%s=%s" % (key, fields[key]))
        if objs:
            obj_parts = []
            for idx in sorted(objs):
                obj_parts.append("[%d]={%s}" % (idx, ",".join(objs[idx])))
            parts.append("Objectives={%s}" % ",".join(obj_parts))
        lines.append("[%d]={%s}," % (qid, ",".join(parts)))
    lines.append("}")
    lines.append("end")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def read_kv(path):
    """[(id, rhs source text)] for every `[id] = value,` row in a data file."""
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        m = KV_RE.match(line)
        if m:
            rows.append((int(m.group(1)), m.group(2)))
    return rows


def resolve_dungeons(questie, dungeon_rows, instances):
    """Which instance each coordinate-less objective row is inside.

    Carbonite's rows write an objective found inside a dungeon in one of two
    ways. Some name the instance's own map id. The rest name the outdoor zone
    the dungeon is entered from and zero the coordinates:
        "Garrett Family Treasure|1418|32|0|0|5.01|3.34"   (Uldaman, via Badlands)
    That form doesn't say which dungeon - a problem wherever a zone leads to
    several (Blackrock Mountain, Ahn'Qiraj, the Barrens, Eastern Plaguelands) -
    and there is only ever one such row per objective, even for an item that
    drops in dungeons all over the world. So the row is taken as "this is
    found inside a dungeon" and QuestieDB is asked which:

      objective  every dungeon QuestieDB finds the row's own objective in
                 (matched by name), whichever zone it is entered from
      quest      QuestieDB doesn't place the objective itself, but ties the
                 quest as a whole to a dungeon entered from the row's zone
      zone       QuestieDB has nothing; the row's zone leads to one instance

    dungeon_rows: [(quest id, objective index, objective name, zone)]
    Returns ({quest id: {objective index: [instance ids]}}, {how: [rows]}).
    """
    by_name, by_owner = {}, {}
    for inst_id, src in instances:
        name, owner = plain(src).split("|")[:2]
        by_name[name] = inst_id
        by_owner.setdefault(int(owner), set()).add(inst_id)

    def instances_in(areas):
        return {by_name[n] for n in questie.dungeons(areas) if n in by_name}

    objectives = {}
    result, report, undecided = {}, {}, []
    for qid, idx, name, zone in dungeon_rows:
        if qid not in objectives:
            objectives[qid] = questie.quest_objectives(qid)
        cands = by_owner.get(zone, set()) | by_owner.get(ZONE_ALIASES.get(zone), set())
        own, whole = set(), set()
        for names, areas in objectives[qid]:
            whole |= areas
            if name.lower() in names:
                own |= areas
        own = instances_in(own)
        quest_area = questie.quest_area(qid)
        whole = instances_in(whole | ({quest_area} if quest_area else set()))

        if (qid, zone) in ROW_DUNGEONS:
            pick, how = set(ROW_DUNGEONS[(qid, zone)]), "manual"
        elif own:
            pick, how = own, "objective"
        elif whole & cands:
            pick, how = whole & cands, "quest"
        elif len(cands) == 1:
            pick, how = cands, "zone"
        else:
            undecided.append((qid, idx, name, zone))
            continue
        report.setdefault(how, []).append((qid, idx, name, zone, sorted(pick), sorted(own | whole)))
        if pick:
            slot = result.setdefault(qid, {}).setdefault(idx, [])
            slot.extend(i for i in sorted(pick) if i not in slot)

    if undecided:
        raise SystemExit(
            "objective rows inside a dungeon that QuestieDB can't place; add them "
            "to ROW_DUNGEONS:\n" + "\n".join(
                "  quest %d objective %d (%s), zone %d" % row for row in undecided))
    return result, report


def resolve_endpoint_dungeons(questie, rows, instances):
    """Instances a quest is picked up or turned in inside, for the rows that
    don't say where that happens.

    A giver inside a dungeon is usually written with the instance's own map
    id, which needs nothing from here. But a good many rows - most of
    Blackrock Depths - carry no Start or End at all, so the quest would have
    no pickup pin and, once complete, nowhere to be sent. QuestieDB knows who
    starts and finishes each quest and where they stand.

    rows: [(quest id, "Start" or "End")]
    Returns {quest id: {"Start": [instance ids], "End": [instance ids]}}.
    """
    by_name = {plain(src).split("|")[0]: inst_id for inst_id, src in instances}
    out = {}
    for qid, key in rows:
        areas = questie.quest_ends(qid, key == "End")
        ids = sorted(by_name[n] for n in questie.dungeons(areas) if n in by_name)
        if ids:
            out.setdefault(qid, {})[key] = ids
    return out


def check_map_flags(addons, instances):
    """The map's entrance flags must be the instances quests are routed to."""
    path = addons / "AlchemyGPS" / "Map" / "Data" / "GuideDungeonEntrance.lua"
    flags = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = MAP_FLAG_RE.match(line)
        if m:
            flags[m.group(1)] = (int(m.group(2)), float(m.group(3)), float(m.group(4)))
    wrong = []
    for _, src in instances:
        name, owner, x, y = plain(src).split("|")
        want = (int(owner), float(x), float(y))
        if flags.get(name) != want:
            wrong.append("  %s: quest data %s, map flag %s" % (name, want, flags.get(name)))
    if wrong:
        raise SystemExit("%s disagrees with Zones.lua:\n%s" % (path.name, "\n".join(wrong)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--addons", default=str(Path(__file__).resolve().parents[2]))
    ap.add_argument("--report", action="store_true",
                    help="list how each dungeon objective row was settled")
    args = ap.parse_args()

    addons = Path(args.addons)
    cam = addons / "Carbonite.Quests" / "Data" / "camelot"
    shared = addons / "Carbonite.Quests" / "Data" / "Shared"
    out_dir = addons / "AlchemyGPS" / "Quest" / "Data"
    out_dir.mkdir(parents=True, exist_ok=True)

    quest_ids = set()
    se_ids = set()
    total_objs = 0
    unplaced = []   # (quest id, objective index, name, map id): rows with zeroed coordinates
    no_endpoint = []    # (quest id, "Start"/"End", map id): no usable pickup / turn-in position
    headers = {}        # quest id -> (side, minimum level)
    for src_name, out_name in QUEST_FILES:
        rows = parse_quest_file(cam / src_name)
        for qid, fields, objs in rows:
            if qid in quest_ids:
                raise SystemExit("duplicate quest id %d in %s" % (qid, src_name))
            quest_ids.add(qid)
            total_objs += sum(len(v) for v in objs.values())
            for idx, obj_rows in objs.items():
                for src in obj_rows:
                    part = plain(src).split("|")
                    try:
                        zone, x, y = int(part[1]), float(part[3]), float(part[4])
                    except (IndexError, ValueError):
                        continue
                    if zone and x == 0 and y == 0:
                        unplaced.append((qid, idx, part[0], zone))
            head = plain(fields.get("Quest", '""')).split("|")
            headers[qid] = tuple(
                int(head[n]) if len(head) > n and head[n].lstrip("-").isdigit() else 0 for n in (1, 3))
            for key in ("Start", "End"):
                zone = x = y = 0
                if key in fields:
                    part = plain(fields[key]).split("|")
                    if part[0].isdigit():
                        se_ids.add(int(part[0]))
                    try:
                        zone, x, y = int(part[1]), float(part[3]), float(part[4])
                    except (IndexError, ValueError):
                        pass
                if x == 0 and y == 0:
                    no_endpoint.append((qid, key, zone))
        emit_quest_file(out_dir / out_name, src_name, rows)
        print("%-16s -> %-13s %5d quests" % (src_name, out_name, len(rows)))

    # Alternate giver/ender spawns (multi-city quests).
    start_alts = [(i, v) for i, v in read_kv(cam / "QuestStartAlts.lua") if i in quest_ids]
    end_alts = [(i, v) for i, v in read_kv(cam / "QuestEndAlts.lua") if i in quest_ids]
    for _, rhs in start_alts + end_alts:
        for entry in plain(rhs).split(";"):
            first = entry.split("|")[0]
            if first.isdigit():
                se_ids.add(int(first))

    # Giver/ender names, resolved in the same order as Carbonite's UnpackSE:
    # NPC table, then object, then item, then the legacy combined table.
    name_tables = [dict(read_kv(cam / n)) for n in (
        "QuestStartEndNPC.lua", "QuestStartEndObject.lua",
        "QuestStartEndItem.lua", "QuestNPC.lua")]
    names = []
    unresolved = []
    for i in sorted(se_ids):
        for table in name_tables:
            if i in table:
                names.append((i, table[i]))
                break
        else:
            unresolved.append(i)

    prev = [(i, v) for i, v in read_kv(shared / "QuestPrev.lua") if i in quest_ids]
    classes = [(i, v) for i, v in read_kv(cam / "QuestRequiredClasses.lua") if i in quest_ids]

    instances = []
    zones_path = addons / "Carbonite" / "Data" / "camelot" / "Zones.lua"
    for line in zones_path.read_text(encoding="utf-8").splitlines():
        m = ZONE_RE.match(line)
        if m:
            owner = OWNER_MAP_FIXES.get(int(m.group(3)), int(m.group(3)))
            ex, ey = ENTRANCE_FIXES.get(int(m.group(1)), (m.group(4), m.group(5)))
            instances.append((int(m.group(1)), '"%s|%d|%s|%s"' % (
                m.group(2), owner, ex, ey)))

    check_map_flags(addons, instances)

    # Rows that name an instance's own map id already say which dungeon; the
    # ones on an outdoor zone are settled from QuestieDB.
    instance_ids = {inst_id for inst_id, _ in instances}
    from questie_db import QuestieDB
    questie = QuestieDB(addons / "QuestieDB")
    dungeons, report = resolve_dungeons(
        questie, [row for row in unplaced if row[3] not in instance_ids], instances)
    objective_dungeons = [
        (qid, '"%s"' % ";".join(
            "%d=%s" % (idx, ",".join(map(str, ids))) for idx, ids in sorted(slots.items())))
        for qid, slots in sorted(dungeons.items())]

    ends = resolve_endpoint_dungeons(
        questie, [(qid, key) for qid, key, zone in no_endpoint if zone not in instance_ids],
        instances)
    endpoint_dungeons = [
        (qid, '"%s|%s"' % (",".join(map(str, found.get("Start", ()))),
                           ",".join(map(str, found.get("End", ())))))
        for qid, found in sorted(ends.items())]

    def block(name, rows, per_line=1):
        out = ["QuestData.%s = {" % name]
        if per_line == 1:
            out.extend("[%d]=%s," % (i, v) for i, v in rows)
        else:
            for n in range(0, len(rows), per_line):
                out.append("".join("[%d]=%s," % (i, v) for i, v in rows[n:n + per_line]))
        out.append("}")
        return out

    lines = [HEADER.format(
        source="Carbonite.Quests/Data/{camelot,Shared}/* and Carbonite/Data/camelot/Zones.lua",
        note="Lookup tables that sit beside the quest rows (see each block below)."),
        "local AlchemyGPS = _G.AlchemyGPS",
        "AlchemyGPS.QuestData = AlchemyGPS.QuestData or {}",
        "local QuestData = AlchemyGPS.QuestData",
        "",
        "-- Giver/ender id -> display name. One table, already resolved in",
        "-- Carbonite's own lookup order (NPC, object, item, legacy), limited to",
        "-- the ids the quest rows and alt lists actually reference.",
    ]
    lines += block("Names", names)
    lines += ["", "-- Quest id -> the quest that must be completed first (reverse of the",
              "-- header's next-id chain link). Filtered to quests in this data set."]
    lines += block("Prev", prev, per_line=8)
    lines += ["", "-- Quest id -> required-class bitmask. WARRIOR=1 PALADIN=2 HUNTER=4",
              "-- ROGUE=8 PRIEST=16 DEATHKNIGHT=32 SHAMAN=64 MAGE=128 WARLOCK=256",
              "-- MONK=512 DRUID=1024."]
    lines += block("RequiredClasses", classes, per_line=8)
    lines += ["", "-- Quest id -> ';'-separated alternate giver strings (same packed",
              "-- shape as a row's own Start), for quests offered in several places."]
    lines += block("StartAlts", start_alts)
    lines += ["", "-- Same, for alternate turn-in points."]
    lines += block("EndAlts", end_alts)
    lines += ["", "-- Instance map id -> \"name|ownerMapId|x|y\": where the instance's",
              "-- entrance sits on its outdoor zone (0-100 zone percent)."]
    lines += block("Instances", instances)
    lines += ["", "-- Quest id -> \"objective=instance,instance;objective=...\": the",
              "-- instances an objective is found inside, for the rows that name only",
              "-- the outdoor zone a dungeon is entered from (coordinates zeroed)",
              "-- and so don't say which dungeon. Worked out from QuestieDB by",
              "-- Tools/gen_quest_data.py's resolve_dungeons."]
    lines += block("ObjectiveDungeons", objective_dungeons)
    lines += ["", "-- Quest id -> \"instances|instances\": the instances a quest is picked",
              "-- up inside | turned in inside, for rows that carry no Start or End",
              "-- position at all. A giver or turn-in whose Start/End names the",
              "-- instance's own map id needs no entry here. Also from QuestieDB."]
    lines += block("EndpointDungeons", endpoint_dungeons, per_line=6)
    (out_dir / "QuestDBExtras.lua").write_text(
        "\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    # Quests QuestieDB has and Carbonite doesn't, and Questie's blacklist.
    from gen_quest_import import read_blacklist, read_holidays, import_rows, write_import
    corrections = addons / "Questie" / "Database" / "Corrections"
    holidays = read_holidays(corrections / "Holidays" / "quests")
    blacklist, unread = read_blacklist(corrections / "QuestieQuestBlacklist.lua")
    blacklist -= holidays
    imported, new_names, new_start_alts, new_end_alts, new_headers, import_counts = import_rows(
        questie, quest_ids, blacklist, holidays)
    known_names = {i for i, _ in names}
    new_names = {i: n for i, n in new_names.items() if i not in known_names}
    write_import(
        questie, out_dir / "QuestDBImported.lua",
        HEADER.format(source="QuestieDB (QuestieDB_Forever.toc) and Questie's QuestieQuestBlacklist.lua",
                      note="Quests the Carbonite data lacks, in its row shape; the quest blacklist."),
        imported, new_names, new_start_alts, new_end_alts, blacklist)
    headers.update(new_headers)

    from gen_quest_rules import write_rules
    counts = write_rules(
        questie, out_dir / "QuestDBRules.lua",
        HEADER.format(source="QuestieDB (QuestieDB_Forever.toc, support/Forever/Zones)",
                      note="Pickup rules, item-started quests, NPC patrol paths and quest items."),
        headers, {**{i: plain(rhs) for i, rhs in names}, **new_names})

    print("quests %d, objective rows %d" % (len(quest_ids), total_objs))
    print("imported from QuestieDB: %s; blacklist %d (%d conditions not understood, %d holiday quests left out)" % (
        ", ".join("%s %d" % kv for kv in import_counts.items()), len(blacklist), unread, len(holidays)))
    print("rules %d, item-started quests %d, patrol paths %d, quests with items %d" % counts)
    print("names %d (unresolved ids: %s)" % (len(names), unresolved or "none"))
    print("prev %d, classes %d, start alts %d, end alts %d, instances %d" % (
        len(prev), len(classes), len(start_alts), len(end_alts), len(instances)))
    print("dungeon objective rows: %s; %d quests" % (
        ", ".join("%s %d" % (how, len(rows)) for how, rows in sorted(report.items())),
        len(objective_dungeons)))
    print("pickup / turn-in inside a dungeon, from QuestieDB: %d / %d quests" % (
        sum(1 for f in ends.values() if "Start" in f), sum(1 for f in ends.values() if "End" in f)))
    if args.report:
        names = {inst_id: plain(src).split("|")[0] for inst_id, src in instances}
        for how, rows in sorted(report.items()):
            print("== %s" % how)
            for qid, idx, name, zone, pick, known in sorted(rows):
                print("  %5d #%d %-40s zone %d -> %s%s" % (
                    qid, idx, name[:40], zone, " / ".join(names[i] for i in pick) or "(none)",
                    "" if set(pick) == set(known) else
                    "   [QuestieDB: %s]" % (" / ".join(names[i] for i in known) or "nothing")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
